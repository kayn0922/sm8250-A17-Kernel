#!/usr/bin/env python3
"""Idempotent "WiFi sharing" fixes for ymdzq/kernel_xiaomi_sm8250_mod (4.19).

Invoked by .github/workflows/build-a17-kernel.yml AFTER apply_patches.sh and
apply_stability_fixes.py, immediately before build.sh.

    python3 scripts/apply_wifi_share_fixes.py \
        --kernel-dir kernel --device enuma \
        --fragment configs/enuma_elish_wifi_share.config
    python3 scripts/apply_wifi_share_fixes.py ... --check   # CI verification

Inputs (kept verbatim in this repository):
  patches/0001-soc-qcom-subsystem_restart-skip-esoc0.patch
  configs/enuma_elish_wifi_share.config

Problem
  enuma hardware (SM8250 + external SDX55M) running the WiFi-only elish ROM
  has no matching modem EFS/calibration. The modem errfatals every ~13 s with
  CRITICAL_DATA_CHECK_FAILED; every errfatal calls subsystem_restart_dev()
  with restart_level RESET_SUBSYS_COUPLED ("RELATED"), which powers cycles
  esoc0 AND the coupled wlan subsystem. That tears down the cnss IMS/COEX QMI
  services and locally deauthenticates the WiFi STA when EasyTether
  (STA + P2P concurrency) is active. Runtime knobs were verified ineffective
  (disable_restart_work, /sys/.../restart_level is read-only), so this must be
  a build-time change.

Two fixes
  1. drivers/soc/qcom/subsystem_restart.c: right after the
     "Restart sequence requested ..." pr_info() and before the
     disable_restart_work check, skip the coupled restart when name == esoc0.
     This is exactly the block in the supplied .patch, but matched by
     structure instead of line numbers: the patch hunk says @@ -1900,6 ...
     while the upstream android16-aptusitu anchor is at line 1239, so a plain
     `git apply` would reject it.
  2. build.sh: inject a WIFI_SHARE_CONFIG block at the END of SET_CONFIG().
     SET_CONFIG() runs after `make <device>_defconfig` and edits the FINAL
     out/.config with scripts/config. Editing only *_defconfig is NOT enough
     on this tree (a previous build showed defconfig additions dropped from
     the shipped /proc/config.gz), hence the injection here. The commands are
     generated by parsing configs/enuma_elish_wifi_share.config, not hardcoded.

Every hunk matches by structure. If an anchor cannot be matched the script
aborts instead of producing a half-patched kernel. Re-running is safe.
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path

SSR_C = "drivers/soc/qcom/subsystem_restart.c"
BUILD_SH = "build.sh"

MARKER_C = 'skipping coupled restart for %s'
MARKER_SH = 'WIFI_SHARE_CONFIG_BEGIN'

# The upstream Kconfig symbol is ESOC_MDM_4x (lower-case x) - the supplied
# fragment says ESOC_MDM_4X. Keep the input file verbatim, correct the symbol
# at generation time, and report it so the discrepancy is visible in CI logs.
SYMBOL_ALIASES = {'ESOC_MDM_4X': 'ESOC_MDM_4x'}

# On WiFi-only devices there is no external modem and no esoc0 DTS node, so
# forcing the ESOC driver family on would only compile in dead code.
MODEM_ONLY_SYMBOLS = {
    'ESOC', 'ESOC_DEV', 'ESOC_CLIENT', 'ESOC_MDM_4x', 'ESOC_MDM_DRV',
}

SSR_BLOCK = (
    '\n'
    '\t/*\n'
    '\t * enuma + elish-ROM quirk: the external SDX55M has no matching EFS /\n'
    '\t * calibration and errfatals every ~13 s.  A coupled ("RELATED")\n'
    '\t * restart here resets the wlan subsystem and the cnss IMS/COEX QMI\n'
    '\t * services, which locally deauthenticates the WiFi STA whenever\n'
    '\t * EasyTether (virp2p + STA/P2P concurrency) is active.  Keep the\n'
    '\t * modem up for GNSS/QMI_LOC, but do not run the coupled restart.\n'
    '\t */\n'
    '\tif (!strcmp(name, "esoc0")) {\n'
    '\t\tpr_warn("subsys-restart: skipping coupled restart for %s\\n", name);\n'
    '\t\treturn 0;\n'
    '\t}\n'
)

# Matches the exact two-line pr_info() plus the blank line that precedes
# `if (disable_restart_work == DISABLE_SSR)`. `\\n` matches the literal
# backslash-n inside the C format string; `\n` matches a real newline.
SSR_ANCHOR = re.compile(
    r'(\tpr_info\("Restart sequence requested for %s, restart_level = %s\.\\n",\n'
    r'[ \t]*name, restart_levels\[dev->restart_level\]\);\n)'
    r'[ \t]*\n'
    r'(\tif \(disable_restart_work == DISABLE_SSR\) \{)'
)

ROOT = Path(".")


def read(rel):
    p = ROOT / rel
    if not p.exists():
        raise SystemExit("MISSING FILE: %s (wrong --kernel-dir?)" % rel)
    return p.read_text(encoding="utf-8", errors="surrogateescape")


def write(rel, text):
    (ROOT / rel).write_text(text, encoding="utf-8", errors="surrogateescape")


def parse_fragment(path, device):
    """Return [(kind, symbol, value)] from a kernel .config fragment."""
    if not path.is_file():
        raise SystemExit("fragment not found: %s" % path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    ops = []
    print("fragment: %s" % path)
    print("fragment-sha256: %s" % digest)
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        m = re.match(r'^CONFIG_([A-Za-z0-9_]+)=(.*)$', line)
        if m:
            sym, val = m.group(1), m.group(2).strip()
            if sym in SYMBOL_ALIASES:
                print("  [NOTE] correcting symbol %s -> %s (upstream Kconfig spelling)"
                      % (sym, SYMBOL_ALIASES[sym]))
                sym = SYMBOL_ALIASES[sym]
            if device != 'enuma' and sym in MODEM_ONLY_SYMBOLS:
                print("  [SKIP] %-38s (WiFi-only device: no external modem)" % sym)
                continue
            ops.append(('enable' if val == 'y' else
                        'module' if val == 'm' else 'set', sym, val))
            continue
        m = re.match(r'^#\s*CONFIG_([A-Za-z0-9_]+) is not set\s*$', line)
        if m:
            sym = m.group(1)
            if sym in SYMBOL_ALIASES:
                sym = SYMBOL_ALIASES[sym]
            ops.append(('disable', sym, ''))
    if not ops:
        raise SystemExit("fragment produced no config operations")
    return ops, digest


def render_injection(ops, digest, device):
    """Build the shell block appended to SET_CONFIG() in build.sh.

    One scripts/config operation per line so that `--set-val SYM VALUE`
    is never split across a backslash continuation.
    """
    parts = []
    for kind, sym, val in ops:
        if kind == 'enable':
            parts.append('-e ' + sym)
        elif kind == 'module':
            parts.append('-m ' + sym)
        elif kind == 'disable':
            parts.append('-d ' + sym)
        else:
            parts.append('--set-val %s %s' % (sym, val))
    lines = [
        '    # --- %s (generated by apply_wifi_share_fixes.py) ---' % MARKER_SH,
        '    # Source: configs/enuma_elish_wifi_share.config',
        '    # Applied to the FINAL out/.config; defconfig-only edits are lost.',
        '    # device=%s fragment-sha256=%s' % (device, digest[:16]),
        '    if [ -f out/.config ]; then',
        '        scripts/config --file out/.config \\',
    ]
    for i, part in enumerate(parts):
        lines.append('            %s%s' % (part, ' \\' if i < len(parts) - 1 else ''))
    lines += [
        '        echo "=== WIFI_SHARE_CONFIG: values in out/.config ==="',
        "        grep -E '^CONFIG_(PANIC_ON_SSR_NOTIF_TIMEOUT|MHI_DEBUG|MHI_UCI|"
        "MHI_SATELLITE|SETUP_SSR_NOTIF_TIMEOUTS|SSR_SYSMON_NOTIF_TIMEOUT|"
        "SSR_SUBSYS_NOTIF_TIMEOUT|ESOC|ESOC_MDM_4x)=' out/.config || true",
        "        grep -E '^# CONFIG_(PANIC_ON_SSR_NOTIF_TIMEOUT|MHI_DEBUG|"
        "MHI_UCI|MHI_SATELLITE) is not set' out/.config || true",
        '    else',
        '        echo "ERROR: out/.config missing in SET_CONFIG"; exit 1',
        '    fi',
        '    # --- WIFI_SHARE_CONFIG_END ---',
        '',
    ]
    return '\n'.join(lines) + '\n'


def fix_ssr():
    t = read(SSR_C)
    if MARKER_C in t:
        return "SKIP (already patched)"
    if 'int subsystem_restart_dev(struct subsys_device *dev)' not in t:
        raise SystemExit("PATCH HUNK FAILED: subsystem_restart_dev() not found")
    new, n = SSR_ANCHOR.subn(
        lambda m: m.group(1) + SSR_BLOCK + '\n' + m.group(2), t, count=1)
    if n != 1:
        raise SystemExit("PATCH HUNK FAILED: 'Restart sequence requested' / "
                         "'disable_restart_work == DISABLE_SSR' anchor not found")
    write(SSR_C, new)
    return "OK"


def locate_set_config_end(t):
    m = re.search(r'(?m)^SET_CONFIG\(\)\s*\{\s*\n', t)
    if not m:
        raise SystemExit("PATCH HUNK FAILED: SET_CONFIG() { not found in build.sh")
    close = re.search(r'(?m)^\}\s*$', t[m.end():])
    if not close:
        raise SystemExit("PATCH HUNK FAILED: end of SET_CONFIG() not found")
    return m.end() + close.start()


def fix_build_sh(injection):
    t = read(BUILD_SH)
    if MARKER_SH in t:
        return "SKIP (already patched)"
    pos = locate_set_config_end(t)
    write(BUILD_SH, t[:pos] + injection + t[pos:])
    return "OK"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--kernel-dir', default='.', help='kernel source root')
    ap.add_argument('--device', default='enuma',
                    help='device codename (enuma applies the full fragment)')
    ap.add_argument('--fragment', required=True, help='path to the .config fragment')
    ap.add_argument('--check', action='store_true',
                    help='verify markers and generated content, never write')
    args = ap.parse_args()

    global ROOT
    ROOT = Path(args.kernel_dir).resolve()
    if not ROOT.is_dir():
        raise SystemExit("kernel dir not found: %s" % ROOT)

    print("wifi-share fixes: root=%s device=%s mode=%s"
          % (ROOT, args.device, 'check' if args.check else 'apply'))
    ops, digest = parse_fragment(Path(args.fragment), args.device)
    print("config operations: %d" % len(ops))
    for kind, sym, val in ops:
        print("  %-8s %-38s %s" % (kind, sym, val))
    injection = render_injection(ops, digest, args.device)

    if args.check:
        ok = True
        ssr = read(SSR_C)
        present = MARKER_C in ssr
        print("  [%s] %-55s %s" % ('OK' if present else 'FAIL', SSR_C, MARKER_C))
        ok &= present
        # The guard must sit between pr_info() and disable_restart_work check.
        i = ssr.find('Restart sequence requested')
        j = ssr.find(MARKER_C)
        k = ssr.find('disable_restart_work == DISABLE_SSR')
        ordered = 0 <= i < j < k
        print("  [%s] %-55s %s" % ('OK' if ordered else 'FAIL', SSR_C,
                                   'guard placed between pr_info and DISABLE_SSR'))
        ok &= ordered
        sh = read(BUILD_SH)
        present = MARKER_SH in sh and injection.strip() in sh
        print("  [%s] %-55s %s" % ('OK' if present else 'FAIL', BUILD_SH,
                                   'SET_CONFIG injection matches fragment'))
        ok &= present
        if not ok:
            raise SystemExit("verification failed - wifi-share fixes are missing")
        print("all wifi-share fixes verified")
        return

    results = [(SSR_C, fix_ssr()), (BUILD_SH, fix_build_sh(injection))]
    for rel, status in results:
        print("  %-55s %s" % (rel, status))
    print("done")


if __name__ == '__main__':
    main()
